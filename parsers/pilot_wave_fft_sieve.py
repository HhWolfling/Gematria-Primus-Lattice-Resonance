#!/usr/bin/env python3
"""
Module: pilot_wave_fft_sieve.py
Description: FFT verification of the 64 Hz acoustic pilot tone against a
             white-noise null. Estimator: zero-padded FFT + parabolic
             interpolation of the magnitude peak.

HONESTY NOTE (read before citing results): the tone is generated by the
repo's own metronomes/pilot_tone_generator.py, which hard-codes
frequency = 64.0. A recovered 64.0 Hz peak is therefore TRUE BY
CONSTRUCTION — it validates the MEASUREMENT CHAIN (can our FFT recover and
resolve an embedded pure tone; how well does it separate 64.0 from
65.41 Hz), NOT any external claim about Cicada recordings. Ledger weight:
instrument calibration only (level L0-adjacent by design).
"""
import math
import wave
import struct
import os
import numpy as np

FS = 44100
SR = 1.0  # swap


def read_wav(path):
    with wave.open(path, "r") as wf:
        n = wf.getnframes()
        fs = wf.getframerate()
        raw = wf.readframes(n)
    x = np.array(struct.unpack("<%dh" % (len(raw) // 2), raw), float)
    return x / 32768.0, fs


def dom_freq(x, fs, zp=8):
    """Dominant frequency via zero-padded FFT + parabolic interpolation."""
    N = len(x)
    win = np.hanning(N)
    nfft = int(2 ** math.ceil(math.log2(N * zp)))
    X = np.abs(np.fft.rfft(x * win, nfft))
    f = np.fft.rfftfreq(nfft, 1.0 / fs)
    k = int(np.argmax(X))
    if 0 < k < len(X) - 1:  # parabolic interpolation on log magnitude
        a, b, c = np.log(X[k - 1:k + 2] + 1e-30)
        d = (a - c) / (2 * (a - 2 * b + c)) if (a - 2 * b + c) != 0 else 0.0
    else:
        d = 0.0
    return f[k] + d * (f[1] - f[0]), X[k], X.mean()


def two_tone_resolvable(fs, N, f1, f2, amp2_db=-6):
    """Can the estimator tell f1 and f2 apart in one window? Generate a pure
    f2 tone, estimate; resolvable iff |est - f2| << |f1 - f2|."""
    t = np.arange(N) / fs
    x = 10 ** (amp2_db / 20) * np.sin(2 * math.pi * f2 * t)
    est, _, _ = dom_freq(x, fs)
    return est, abs(est - f2)


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    wav = os.path.join(here, "mythos", "pilot_wave_64hz.wav")
    if not os.path.exists(wav):
        print("[!] no wav: run metronomes/pilot_tone_generator.py first "
              "(x -> mythos/pilot_wave_64hz.wav)")
        return
    x, fs = read_wav(wav)
    f0, amp, floor = dom_freq(x, fs)
    snr_db = 20 * math.log10(amp / (floor + 1e-30))

    # White-noise null: dominant-frequency distribution of same-length noise
    N = len(x)
    rng = np.random.default_rng(2026)
    null = np.array([dom_freq(rng.standard_normal(N), fs)[0] for _ in range(1000)])
    # Proper null p-value: how often does RAW noise's dominant frequency land
    # within +-0.5 Hz of our claimed 64.0? (Noise dominant freq is uniform
    # over the band, so this p ~ band share, and that is exactly the point.)
    win = 0.5
    p_near = (np.abs(null - 64.0) <= win).mean()

    # Resolution check: can the instrument tell 64.0 from 65.41 in this window?
    est2, err2 = two_tone_resolvable(fs, N, 64.0, 65.41)

    print(f"file                : {os.path.basename(wav)}")
    print(f"length / fs         : {N} samples @ {fs} Hz ({N/fs:.2f} s)")
    print(f"dominant frequency  : {f0:.4f} Hz  (claim: 64.0 Hz, err {abs(f0-64.0):.4f} Hz)")
    print(f"peak / mean mag     : {amp:.1f} / {floor:.1f}  -> SNR {snr_db:.1f} dB")
    print(f"white-noise null    : dominant freq uniform {null.min():.0f}-{null.max():.0f} Hz "
          f"(mean {null.mean():.0f}, 1000 real., seed 2026)")
    print(f"null p-value        : p(|noise peak - 64.0| <= 0.5 Hz) = {p_near:.4f}")
    print(f"two-tone resolution : pure 65.41 Hz tone estimated at {est2:.4f} Hz "
          f"(err {err2:.4f} Hz) -> 64.0 vs 65.41 separable: "
          f"{'YES' if abs(f0-est2) > 10*max(abs(f0-64.0), err2) else 'NO'}")
    print("[=] truth-by-construction reminder: generator hard-codes 64.0; "
          "result calibrates the instrument, it does not confirm lore.")


if __name__ == "__main__":
    main()
